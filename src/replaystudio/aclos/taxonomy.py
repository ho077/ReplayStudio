def agent_display(agent_id, agent_name):
    """Return the Chinese agent name.

    IMPORTANT (learned from real data, see docs/devlog/002): ACLOS's
    `match.agent.agent_id` is *account-scoped* — it stays identical across all
    605 matches of an account even while the player switches agents. The agent
    actually played lives in `agent_name` ("Yoru", "Reyna", …). Resolving by id
    first therefore mislabels every match as the account's first-ever agent.
    """
    if agent_name:
        cn = AGENT_CN_BY_EN.get(agent_name)
        if cn:
            return cn
        # Only trust the uuid table when it agrees with the English name.
        pair = AGENT_NAME_BY_UUID.get(agent_id or "")
        if pair and pair[1] and pair[0] == agent_name:
            return pair[1]
        return agent_name
    pair = AGENT_NAME_BY_UUID.get(agent_id or "")
    if pair and pair[1]:
        return pair[1]
    return agent_id or "未知特工"


def map_display(map_id):
    cn = MAP_CN_BY_URL.get(map_id or "")
    if cn:
        return cn
    if map_id:
        return map_id.rstrip("/").split("/")[-1]
    return "未知地图"


def mode_display(mode, mode_name):
    """Chinese game-mode name.

    `mode` is the short ACLOS token ("competitive", "aros", …) and is the most
    reliable signal; `mode_name` is the Unreal asset path, used as a fallback.
    """
    if mode:
        cn = MODE_CN_BY_SHORT.get(str(mode).strip().lower())
        if cn:
            return cn
    for hint, cn in MODE_CN_BY_PATH_HINT.items():
        if mode_name and hint.lower() in str(mode_name).lower():
            return cn
        if mode and hint.lower() in str(mode).lower():
            return cn
    if mode and MODE_CN_BY_EN.get(mode):
        return MODE_CN_BY_EN[mode]
    return mode or mode_name or "未知模式"
