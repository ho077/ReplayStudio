"""Generate src/replaystudio/aclos/taxonomy.py from the reference registry.

The registry (WonderfulUI, GPL-3.0-or-later) carries Riot's own zh-CN display
names. We only extract factual name mappings (uuid/mapUrl -> Chinese label),
which are game content facts, not creative code. ReplayStudio re-emits them as
its own data table so the runtime never parses TypeScript.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "WonderfulUI", "packages", "gui", "src",
                   "utils", "generated", "valorant-metadata.zh-CN.ts")
DST = os.path.join(ROOT, "src", "replaystudio", "aclos", "taxonomy.py")


def blocks(text, start_marker, end_marker):
    i = text.index(start_marker)
    j = text.index(end_marker, i)
    return text[i:j]


def parse_objs(seg):
    out = []
    for m in re.finditer(r"\{(.*?)\}", seg, re.S):
        body = m.group(1)
        d = {}
        for k in ("uuid", "en", "cn", "mapUrl", "assetPath", "developerName"):
            mm = re.search(r'"%s":\s*"([^"]*)"' % k, body)
            if mm:
                d[k] = mm.group(1)
        if d:
            out.append(d)
    return out


def main():
    text = open(SRC, encoding="utf-8").read()
    agents = parse_objs(blocks(text, "VALORANT_AGENTS", "VALORANT_MAPS"))
    maps = parse_objs(blocks(text, "VALORANT_MAPS", "VALORANT_GAME_MODES"))
    modes = parse_objs(blocks(text, "VALORANT_GAME_MODES", "VALORANT_SKINS")
                       if "VALORANT_SKINS" in text else text[text.index("VALORANT_GAME_MODES"):])

    agent_by_uuid = {a["uuid"]: (a.get("en", ""), a.get("cn", "")) for a in agents if a.get("uuid")}
    agent_by_en = {a.get("en", ""): a.get("cn", "") for a in agents if a.get("en")}
    map_by_url = {m["mapUrl"]: m.get("cn", "") for m in maps if m.get("mapUrl")}
    mode_cn = {m.get("en", ""): m.get("cn", "") for m in modes if m.get("cn")}
    mode_asset = {m.get("assetPath", ""): m.get("cn", "") for m in modes if m.get("assetPath")}

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8") as f:
        f.write('"""zh-CN display names for VALORANT maps / agents / game modes.\n\n')
        f.write("Generated by tools/build_taxonomy.py from the local reference registry\n")
        f.write("(WonderfulUI, GPL-3.0-or-later). Only factual display names are stored.\n")
        f.write("Unknown ids fall back to the raw ACLOS value; users can correct labels\n")
        f.write("in Settings -> Metadata overrides.\n")
        f.write('"""\n\n')
        f.write("AGENT_NAME_BY_UUID = " + json.dumps(agent_by_uuid, ensure_ascii=False, indent=4) + "\n\n")
        f.write("AGENT_CN_BY_EN = " + json.dumps(agent_by_en, ensure_ascii=False, indent=4) + "\n\n")
        f.write("MAP_CN_BY_URL = " + json.dumps(map_by_url, ensure_ascii=False, indent=4) + "\n\n")
        f.write("MODE_CN_BY_EN = " + json.dumps(mode_cn, ensure_ascii=False, indent=4) + "\n\n")
        f.write("MODE_CN_BY_ASSET = " + json.dumps(mode_asset, ensure_ascii=False, indent=4) + "\n\n")

        f.write('''# Fallbacks for game modes identified only by their unreal asset path.
MODE_CN_BY_PATH_HINT = {
    "Bomb/competitive": "竞技模式",
    "Bomb/unrated": "标准模式",
    "Bomb/premier": "超凡晋级赛",
    "Swiftplay": "极速模式",
    "Spikerush": "爆能快攻",
    "Deathmatch": "死斗",
    "Escalation": "武装升级",
    "Replication": "复制模式",
    "SnowballFight": "雪球大战",
    "Dodgeball": "躲避球",
    "AROS": "爆能大乱斗",
    "TeamDeathmatch": "团队死斗",
    "Range": "靶场",
}

# Video types that are montages (highlight reels) rather than single moments.
MONTAGE_TYPES = {"击杀集锦", "死亡集锦"}

VIDEO_TYPE_ORDER = [
    "五杀时刻", "四杀时刻", "三杀时刻", "击杀集锦", "死亡集锦",
    "段位晋级", "夜市翻牌",
]


def agent_display(agent_id, agent_name):
    """Return Chinese display name for an agent; never invent a label."""
    pair = AGENT_NAME_BY_UUID.get(agent_id or "")
    if pair and pair[1]:
        return pair[1]
    if agent_name and AGENT_CN_BY_EN.get(agent_name):
        return AGENT_CN_BY_EN[agent_name]
    return agent_name or agent_id or "未知特工"


def map_display(map_id):
    cn = MAP_CN_BY_URL.get(map_id or "")
    if cn:
        return cn
    if map_id:
        return map_id.rstrip("/").split("/")[-1]
    return "未知地图"


def mode_display(mode, mode_name):
    for hint, cn in MODE_CN_BY_PATH_HINT.items():
        if mode_name and hint.lower() in mode_name.lower():
            return cn
        if mode and hint.lower() in str(mode).lower():
            return cn
    if mode and MODE_CN_BY_EN.get(mode):
        return MODE_CN_BY_EN[mode]
    return mode or mode_name or "未知模式"
''')
    print("agents:", len(agent_by_uuid), "maps:", len(map_by_url), "modes:", len(mode_cn))
    print("WROTE", DST)


